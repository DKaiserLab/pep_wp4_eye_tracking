function d = compare_task_RDMs_between_experiments(d, cfg)
% COMPARE_TASK_RDMS_BETWEEN_EXPERIMENTS
%
% Compare the correlation between a gaze IS-RDM and predictor IS-RDMs
% between two experiments.
%
% Assumptions:
%   - Full IS-RDMs contain 68 subjects.
%   - Subjects 1:34 belong to Experiment 1.
%   - Subjects 35:68 belong to Experiment 2.
%   - The predictor IS-RDMs have the same 68-subject structure.
%
% The permutation test shuffles the rows and columns of the 68x68
% gaze/reference RDM and then splits the shuffled RDM into two 34x34
% experiment blocks. The predictor RDMs remain fixed.
%
% The test statistic is:
%
%       delta_r = r_exp1 - r_exp2
%
% and the p-value is based on the permutation distribution of delta_r.


% Configuration
if ~isfield(cfg, 'RDM_to_partial_out')
    cfg.RDM_to_partial_out = { ...
        'Typcial Drawings Style', ...
        'Photos vgg16_imagenet Late', ...
        'Control Images vgg16_imagenet Late', ...
        'Typical Images vgg16_imagenet Late', ...
        'Survey responses'};
end

if ~isfield(cfg, 'correlation_type'); cfg.correlation_type = 'spearman'; end
if ~isfield(cfg, 'permutation_test'); cfg.permutation_test = false; end
if ~isfield(cfg, 'n_permutations'); cfg.n_permutations = 10000; end
if ~isfield(cfg, 'partial_cor'); cfg.partial_cor = true; end
if ~isfield(cfg, 'save_name'); cfg.save_name = 'compare_task_RDMs_between_experiments'; end


% Basic settings
nTotal = 68;
nExp = round(nTotal/2);

exp1_idx = 1:nExp;
exp2_idx = (nExp+1):nTotal;

assert(cfg.n == nTotal, ...
    'cfg.n must be 68 for this between-experiment analysis.');


% Prepare permutation sequences
if cfg.permutation_test

    rng(1); % reproducibility
    random_seqs = zeros(cfg.n_permutations, nTotal);

    for perm = 1:cfg.n_permutations
        random_seqs(perm,:) = randperm(nTotal);
    end
end


% Loop through variables of interest
for voi_n = 1:numel(cfg.variables_of_interest)

    voi = char(cfg.variables_of_interest(voi_n));


    % Loop through categories
    for cate_num = 1:numel(cfg.categories)

        category = char(cfg.categories{cate_num});


        % Get gaze/reference RDM
        all_ref_names = {d.([category,'_RDM']).ratingRDM.name};

        ref_idx = find(strcmp(all_ref_names, voi));

        if isempty(ref_idx)

            % If the RDM needs to be generated by evaluate_predictor_RDMs
            temp_predictor_RDMs = cfg.predictor_RDMs;

            cfg.predictor_RDMs = {voi};

            RDMs_tmp = d.([category,'_RDM']).ratingRDM(1);
            labels_tmp = {RDMs_tmp.name};

            [ref_RDM, cfg.labels] = evaluate_predictor_RDMs( ...
                d, RDMs_tmp, labels_tmp, cfg, category);

            cfg.predictor_RDMs = temp_predictor_RDMs;

            ref_RDM = ref_RDM(2:end);
            cfg.labels = cfg.labels(2:end);

        else

            ref_RDM = d.([category,'_RDM']).ratingRDM(ref_idx);

        end

        % Get predictor RDMs
        RDMs = ref_RDM;
        labels = {ref_RDM.name};
        [RDMs, cfg.labels] = evaluate_predictor_RDMs( ...
            d, RDMs, labels, cfg, category);

        % Rename RDMs
        for field = 1:numel({RDMs.name})
            RDMs(field).name = char(cfg.labels{field});
        end

        % Observed correlations
        nPredictors = numel(RDMs) - 1;

        % Build RDM set for Experiment 1
        RDMs_exp1 = RDMs;
        for iRDM = 1:numel(RDMs)
            current_RDM = RDMs(iRDM);
            current_RDM.RDM = current_RDM.RDM(exp1_idx, exp1_idx);
            RDMs_exp1(iRDM) = current_RDM;
        end

        % Correlation Experiment 1
        if cfg.partial_cor
            [~, r_mat_exp1, ~, ~] = partial_cor_RDM(cfg, RDMs_exp1);
        else
            [~, r_mat_exp1, ~] = cor_RDM(RDMs_exp1, cfg);
        end

        % Build RDM set for Experiment 2
        RDMs_exp2 = RDMs;
        for iRDM = 1:numel(RDMs)
            current_RDM = RDMs(iRDM);
            current_RDM.RDM = current_RDM.RDM(exp2_idx, exp2_idx);
            RDMs_exp2(iRDM) = current_RDM;
        end

        % Correlation Experiment 2
        if cfg.partial_cor
            [~, r_mat_exp2, ~, ~] = partial_cor_RDM(cfg, RDMs_exp2);
        else
            [~, r_mat_exp2, ~] = cor_RDM(RDMs_exp2, cfg);
        end

        r_exp1 = r_mat_exp1(1, 2:end)';
        r_exp2 = r_mat_exp2(1, 2:end)';

        % Difference between experiments
        delta_r = r_exp1 - r_exp2;

        % Permutation test
        if cfg.permutation_test

            perm_delta_r = nan(nPredictors, cfg.n_permutations);

            for perm = 1:cfg.n_permutations

                % Shuffle subjects in the full RDMs
                random_order = random_seqs(perm,:);

                % Build RDM set for Experiment 1
                RDMs_exp1 = RDMs;
                for iRDM = 1:numel(RDMs)
                    current_RDM = RDMs(iRDM);
                    if iRDM == 1
                        current_RDM.RDM = current_RDM.RDM(random_order, random_order); % shuffle before group assignment
                    end
                    current_RDM.RDM = current_RDM.RDM(exp1_idx, exp1_idx);
                    RDMs_exp1(iRDM) = current_RDM;
                end

                % Correlation Experiment 1
                if cfg.partial_cor
                    [~, r_mat_exp1, ~, ~] = partial_cor_RDM(cfg, RDMs_exp1);
                else
                    [~, r_mat_exp1, ~] = cor_RDM(RDMs_exp1, cfg);
                end

                % Build RDM set for Experiment 2
                RDMs_exp2 = RDMs;
                for iRDM = 1:numel(RDMs)
                    current_RDM = RDMs(iRDM);
                    if iRDM == 1
                        current_RDM.RDM = current_RDM.RDM(random_order, random_order); % shuffle before group assignment
                    end
                    current_RDM.RDM = current_RDM.RDM(exp2_idx, exp2_idx);
                    RDMs_exp2(iRDM) = current_RDM;
                end

                % Correlation Experiment 2
                if cfg.partial_cor
                    [~, r_mat_exp2, ~, ~] = partial_cor_RDM(cfg, RDMs_exp2);
                else
                    [~, r_mat_exp2, ~] = cor_RDM(RDMs_exp2, cfg);
                end

                % Store difference
                r_perm_exp1 = r_mat_exp1(1, 2:end);
                r_perm_exp2 = r_mat_exp2(1, 2:end);
                perm_delta_r(:, perm) = r_perm_exp1 - r_perm_exp2;

                % Progress
                if mod(perm, round(cfg.n_permutations/10)) == 0
                    disp([num2str((perm/cfg.n_permutations)*100), ...
                        '% of permutations of ', voi, ' ', category, ' is done']);
                end
            end

            % Calculate p values
            p_val = nan(nPredictors,1);

            for pred = 1:nPredictors

                % Two-sided test:
                p_val(pred) = (sum(abs(perm_delta_r(pred,:)) >= ...
                    abs(delta_r(pred))) + 1) / (cfg.n_permutations + 1);

            end

            % Store permutation results
            d.compare_task_between_experiments.permutation_test.(voi).(category).perm_delta_r = perm_delta_r;

        else
            perm_delta_r = [];
            p_val = nan(nPredictors,1);

        end

        % Store observed results
        res_table = table;
        res_table.name = cfg.labels(2:end)';
        res_table.r_exp1 = r_exp1;
        res_table.r_exp2 = r_exp2;
        res_table.delta_r = delta_r;
        res_table.p_val = p_val;

        d.compare_task_between_experiments.(voi).(category) = res_table;

        % Also store the two individual experiment results
        d.compare_task_between_experiments.(voi).(category).r_exp1 = r_exp1;
        d.compare_task_between_experiments.(voi).(category).r_exp2 = r_exp2;
        d.compare_task_between_experiments.(voi).(category).delta_r = delta_r;
    end

    if cfg.permutation_test
        % Categories combined
        cate_mean_delta_r = zeros(height(res_table), 1);
        cate_mean_per_delta_r = zeros(height(res_table), cfg.n_permutations);
        combined_p = cate_mean_delta_r;
        for pred = 1:height(res_table)
            cate_mean_delta_r(pred) = (d.compare_task_between_experiments.(voi).(cfg.categories{1}).delta_r(pred) + ...
                d.compare_task_between_experiments.(voi).(cfg.categories{2}).delta_r(pred))/2;
            cate_mean_per_delta_r(pred, :) = ...
                (d.compare_task_between_experiments.permutation_test.(voi).(cfg.categories{1}).perm_delta_r(pred,:) + ...
                d.compare_task_between_experiments.permutation_test.(voi).(cfg.categories{2}).perm_delta_r(pred, :))/2;

            % get combined p value (Two-sided test)
            combined_p(pred) = (sum(abs(cate_mean_per_delta_r(pred, :)) >= ...
                abs(cate_mean_delta_r(pred))) + 1) / (cfg.n_permutations + 1);
        end

        d.compare_task_between_experiments.combined(voi_n).voi = voi;
        d.compare_task_between_experiments.combined(voi_n).delta_r = cate_mean_delta_r;
        d.compare_task_between_experiments.combined(voi_n).combined_p = combined_p;
    end
end


% Display results
for voi_n = 1:numel(cfg.variables_of_interest)

    voi = char(cfg.variables_of_interest(voi_n));

    disp(newline)
    disp(['================ ', voi, ' ================'])

    for pred = 1:height(res_table)
        disp(['  ', char(res_table.name(pred))])
        disp(['    Difference (Exp1 - Exp2) = ', num2str(d.compare_task_between_experiments.combined(voi_n).delta_r(pred))])
        disp(['    p = ', num2str(d.compare_task_between_experiments.combined(voi_n).combined_p(pred))])
    end
end

end